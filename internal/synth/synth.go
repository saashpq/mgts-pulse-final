// Responses — все ответы синтетического датасета под структуру survey.Default().
func Responses(sv survey.Survey) []survey.Response {
	var out []survey.Response
	for _, p := range sv.Participant {
		for _, role := range []survey.Role{survey.Intern, survey.Mentor} {
			src := intern
			person := p.Intern
			if role == survey.Mentor {
				src, person = mentor, p.Mentor
			}
			rows, ok := src[p.ID]
			if !ok {
				continue
			}
			var scales, texts []survey.Question
			for _, q := range sv.ByRole(role) {
				if q.Kind == "scale" {
					scales = append(scales, q)
				} else {
					texts = append(texts, q)
				}
			}
			for m, r := range rows {
				if r.scores == nil {
					continue
				}
				resp := survey.Response{ID: fmt.Sprintf("%s-%s-M%d", p.ID, role, m+1), Role: role, Person: person, PairID: p.ID,
					Period: m + 1, Scores: map[string]float64{}, Comments: map[string]string{}, Source: "synthetic"}
				for i, q := range scales {
					if i < len(r.scores) {
						resp.Scores[q.Code] = r.scores[i]
					}
				}
				if len(texts) > 0 && r.comment != "" {
					resp.Comments[texts[0].Code] = r.comment
				}
				out = append(out, resp)
			}
		}
	}
	return out
}
