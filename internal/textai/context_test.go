package textai

import (
	"context"
	"testing"
)

func TestCriticalThemeContext(t *testing.T) {
	for _, c := range []struct {
		text, theme, quote string
	}{
		{"Завтра хочу уйти на обед пораньше.", "attrition", ""},
		{"Я не собираюсь увольняться.", "attrition", ""},
		{"Собираюсь уйти из команды.", "attrition", "Собираюсь уйти из команды."},
		{"Разбирали конфликт зависимостей в сборке.", "conflict", ""},
		{"Пока конфликтов с руководителем нет.", "conflict", ""},
		{"Он допустил грубую ошибку в документе.", "conflict", ""},
		{"Наставник постоянно унижает меня при других.", "conflict", "Наставник постоянно унижает меня при других."},
		{"Планирую прервать свою стажировку.", "attrition", "Планирую прервать свою стажировку."},
		{"Я решил досрочно завершить стажировку.", "attrition", "Я решил досрочно завершить стажировку."},
		{"Не хочу прекращать стажировку.", "attrition", ""},
		{"Прервать стажировку можно по заявлению.", "attrition", ""},
		{"Хочу прекратить программу диагностики на стенде.", "attrition", ""},
		{"Хочу покинуть командировку на день раньше.", "attrition", ""},
		{"Я хочу завершить стажировку в срок.", "attrition", ""},
		{"Обсуждали, как уволиться по закону.", "attrition", ""},
		{"Я не увольняюсь.", "attrition", ""},
		{"Коллеги высмеивают стажёрку на встречах.", "conflict", "Коллеги высмеивают стажёрку на встречах."},
		{"Надо мной насмехаются на планёрке.", "conflict", "Надо мной насмехаются на планёрке."},
		{"Коллеги не высмеивают стажёров.", "conflict", ""},
		{"На семинаре обсуждали, почему нельзя высмеивать стажёров.", "conflict", ""},
		{"Ревьюер высмеял идею автоматической сборки.", "conflict", ""},
		{"Вместе с наставником разобрали конфликт зависимостей.", "conflict", ""},
		{"Руководитель больше не смеётся надо мной, но коллега высмеял меня на встрече.", "conflict", "Руководитель больше не смеётся надо мной, но коллега высмеял меня на встрече."},
		{"Раньше нагрузку снизили. Сейчас снова перерабатываю.", "overload", "Сейчас снова перерабатываю."},
		{"Теперь загрузка снова комфортна.", "overload", ""},
		{"После снижения нагрузки успеваю завершить задачи.", "overload", ""},
		{"Проверим нагрузку на следующей встрече.", "overload", ""},
		{"Из-за двух срочных поручений нагрузка стала слишком высокой.", "overload", "Из-за двух срочных поручений нагрузка стала слишком высокой."},
		{"Обсудили конфликт версий. Между мной и наставником возник конфликт.", "conflict", "Между мной и наставником возник конфликт."},
	} {
		a := (Offline{}).Analyze(context.Background(), c.text, "intern")
		if contains(a.Themes, c.theme) != (c.quote != "") || a.ByTheme[c.theme] != c.quote {
			t.Errorf("%q: got theme %v, quote %q; want %q", c.text, a.Themes, a.ByTheme[c.theme], c.quote)
		}
	}
}
